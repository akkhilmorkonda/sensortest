"""The limit sets (D-051, D-056): L-v1 froze L-v0's values; L-v2 is what the station runs now.

Both were generated by benchtop_testing/tools/derive_limits.py (the D-019 rule through the
station's code, D-050). test_golden_lv0.py proves the rule reproduces them; these checks pin what
changed between versions.
"""

import yaml

from conftest import CONFIG
from sensortest.app.settings import load_settings
from sensortest.plans.compiler import compile_plans

AMPLITUDE = {"6040 T10_AMPLITUDE", "3040 T5_AMPLITUDE", "4040 T15_AMPLITUDE"}


def _load(name: str) -> dict:
    return yaml.safe_load((CONFIG / name).read_text(encoding="utf-8"))


def test_l_v1_has_exactly_the_l_v0_values() -> None:
    v0, v1 = _load("archive/TP-001_limits_v0.yaml"), _load("archive/TP-001_limits_v1.yaml")
    assert v1.keys() == v0.keys()
    assert {k for k in v0 if v0[k] != v1[k]} == {"limit_set", "status"}
    for sid, want in v0["steps"].items():
        assert v1["steps"][sid] == want, sid
    assert (v1["limit_set"], v1["plan"]) == ("L-v1", "TP-001")
    assert v1["status"].startswith("frozen 2026-11-08 (D-051)")


def test_l_v2_is_l_v1_without_phase_and_a_0_2_higher_amplitude_ceiling() -> None:
    v1, v2 = _load("archive/TP-001_limits_v1.yaml"), _load("TP-001_limits_v2.yaml")
    assert {k for k in v1 if v1[k] != v2[k]} == {"limit_set", "status", "steps", "validity"}
    integrity1, integrity2 = v1["validity"]["1900 RUN_INTEGRITY"], v2["validity"]["1900 RUN_INTEGRITY"]
    assert (
        integrity1.pop("actuator_stopped_max") == 100.0 and integrity1 == integrity2
    )  # E207 dropped (D-057)
    kept = {sid: d for sid, d in v1["steps"].items() if "PHASE" not in sid}
    assert v2["steps"].keys() == kept.keys()  # the three phase steps are gone
    for sid, want in kept.items():
        got = v2["steps"][sid]
        if sid in AMPLITUDE:  # amplitude now fitted at the measured frequency (D-056)
            assert (got["low"], got["high"]) == (want["low"], 1128.5) and want["high"] == 1128.3
        else:
            assert got == want, sid
    assert v2["limit_set"] == "L-v2" and v2["status"].startswith("2026-11-08 (D-056)")


def test_the_station_runs_l_v2_without_phase() -> None:
    s = load_settings(CONFIG / "settings.yaml")
    assert s.limits.name == "TP-001_limits_v2.yaml"
    plans = compile_plans(s.sensor_tests, s.limits, s.plans, s.plan_constants)
    assert {p.limit_set for p in plans.values()} == {"L-v2"}
    assert {p.plan_version for p in plans.values()} == {"v2.1"}
    assert [st.id for st in plans["PROD"].steps] == [1000, 2040, 2050, 6040, 6050, 1900]
    assert len(plans["ENG"].steps) == 2 + 14
    assert not any(st.name.endswith("_PHASE") for p in plans.values() for st in p.steps)
    t10 = plans["PROD"].limits[6040]
    assert (t10.low, t10.high) == (712.8, 1128.5)
