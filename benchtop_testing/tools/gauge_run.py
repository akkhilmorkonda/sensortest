"""Gauge run before freezing L-v1 (D-019 risk 3, D-051): the real sequences on the device.

Runs PROD and ENG ~20 times each on the Teensy through the station's own headless runner and
drivers, saves every run record, and checks the pass rule chosen on 2026-11-08:

  1. zero ERRORs (and no aborts);
  2. zero false fails: every run gives the expected verdict and primary failure on all 8 sensors
     (ch1 Weak response, ch4 Noisy, ch5 Offset out of range, ch8 Wrong frequency, the rest PASS);
  3. no drift since DOE-1: for every sensor and measured step, the gauge mean lies within
     3 DOE-1 run-to-run SDs of the DOE-1 mean at the same frequency (DOE-1 recomputed with the
     station's code, D-050).

A run whose cause is identified and is not drift can be excluded from rule 3 only, by listing it in
EXCLUDED with its reason (D-051). The report keeps the as-run result next to the result without
the exclusions; rules 1 and 2 always count every run. The exit code is the result with them.

Device safety: the station's Teensy drivers send only `baseline` and `response:5/10/15`, refuse
134 baud, and leave the device in `baseline`.

Usage:
  python benchtop_testing/tools/gauge_run.py run        # 20 PROD + 20 ENG, then analyze
  python benchtop_testing/tools/gauge_run.py analyze    # re-analyze the saved records
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics as st
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

BENCH = Path(__file__).resolve().parents[1]
REPO = BENCH.parent
OUT = BENCH / "05_gauge_run_l_v1"
SERIAL = "TEENSY-20071290"  # the DUT: the one Teensy (USB serial 20071290)
DRIFT_K = 3.0  # rule 3: |gauge mean - DOE-1 mean| <= 3 x DOE-1 run-to-run SD
# expected primary failure family per sensor (TP-001 §8); None = PASS
EXPECTED = {"ch1": "gain", "ch2": None, "ch3": None, "ch4": "noise",
            "ch5": "offset", "ch6": None, "ch7": None, "ch8": "frequency"}
# measured step -> (DOE-1 table column, DOE-1 tone the comparison uses; None = every run)
DOE_REF = {
    "BL_OFFSET": ("BL_OFFSET", None), "BL_NOISE_STD": ("BL_NOISE_STD", None),
    "T5_AMPLITUDE": ("AMPLITUDE", 5), "T10_AMPLITUDE": ("AMPLITUDE", 10), "T15_AMPLITUDE": ("AMPLITUDE", 15),
    "T5_FREQUENCY": ("FREQUENCY", 5), "T10_FREQUENCY": ("FREQUENCY", 10), "T15_FREQUENCY": ("FREQUENCY", 15),
    "REC_TONE_ABSENT": ("REC_TONE_ABSENT", 15), "REC_OFFSET_SHIFT": ("REC_OFFSET_SHIFT", 15),
}  # ENG's REC follows T15; DOE-1's REC follows its own tone
# Runs excluded from rule 3 (run ID -> reason). Decided 2026-11-08 (D-051): freeze L-v1 with this run
# excluded, because its cause is identified (the actuator's tone phase jump, not drift).
EXCLUDED = {
    "R20261108-002546-4793": (
        "ENG. The actuator's tone jumped +118° in one sample at T10 line 265 of 300 (1.77 s into the "
        "window), on every healthy channel at once: the Teensy's 32-bit microsecond counter wrapping "
        "(predicted +117.7° at 10 Hz, and −124.5° at 20 Hz, measured −125.2° on ch8). The one-sine "
        "amplitude fit then reads 82.5–82.8 % of normal (84 % predicted). Not drift: without this run "
        "every ENG T10 amplitude is within 0.4 a.u. of DOE-1. Rules 1 and 2 still count it; they "
        "passed only because its two changed step results were masked by primary failures (ch5 "
        "6040 read 662, a false step FAIL; ch4 6040 read 982, a missed step FAIL). Re-measure with "
        "`tools/phase_jump.py`."
    ),
}


class Tee:
    def __init__(self, *streams):
        self.streams = streams

    def write(self, s):
        for x in self.streams:
            x.write(s)
            x.flush()

    def flush(self):
        for x in self.streams:
            x.flush()


def gauge_settings() -> Path:
    """config/settings.yaml with the Teensy fixture and records in OUT/records (kept as provenance)."""
    s = yaml.safe_load((REPO / "config" / "settings.yaml").read_text(encoding="utf-8"))
    s["active_fixture"] = "teensy"
    s["data_dir"] = "records"
    s["sensor_tests"] = "../../config/" + s["sensor_tests"]
    s["limits"] = "../../config/" + s["limits"]
    s["fixtures"]["replay"]["links"]["doe1"]["data_dir"] = "../03_doe1_repeatability"
    path = OUT / "settings_gauge.yaml"
    OUT.mkdir(parents=True, exist_ok=True)
    path.write_text("# GENERATED by benchtop_testing/tools/gauge_run.py from config/settings.yaml (D-051)\n"
                    + yaml.safe_dump(s, sort_keys=False), encoding="utf-8")
    return path


def run(n: int) -> None:
    from sensortest.app.headless import run_headless

    settings = gauge_settings()
    with (OUT / "console.log").open("a", encoding="utf-8") as log:
        out = Tee(sys.stdout, log)
        for seq in ("PROD", "ENG"):
            print(f"--- {seq} x{n}", file=out)
            code = run_headless(settings, seq, n, SERIAL, out=out, fixture="teensy")
            if code:
                sys.exit(f"headless runner exited with code {code}; gauge run stopped")


# ---------------------------------------------------------------- analysis ----
def load_records():
    runs = []
    for f in sorted((OUT / "records").rglob(f"{SERIAL}_*.csv")):
        if f.name.endswith("_raw.csv"):
            continue
        rows = list(csv.DictReader(f.open(newline="", encoding="utf-8")))
        meta = json.loads(next(r["metadata"] for r in rows if r["metadata"]))
        runs.append({"file": f.name, "run_id": f.stem.split("_", 1)[1], "rows": rows, "meta": meta,
                     "sequence": rows[0]["sequence"], "outcome": rows[0]["outcome"],
                     "error": rows[0]["error_code"], "limit_set": rows[0]["limit_set"]})
    return runs


def doe_reference():
    from sensortest.app.settings import load_settings
    from sensortest.characterization.recut import load_doe
    from sensortest.characterization.table import metric_rows
    from sensortest.plans.compiler import compile_plans

    s = load_settings(REPO / "config" / "settings.yaml")
    plans = compile_plans(s.sensor_tests, s.limits, s.plans, s.plan_constants)
    rows = metric_rows(load_doe(BENCH / "03_doe1_repeatability", plans["ENG"]), plans["ENG"])
    ref = {}
    for step, (col, f) in DOE_REF.items():
        for ch in range(1, 9):
            v = [r[col] for r in rows if r["ch"] == ch and col in r
                 and (f is None or r.get("f") == float(f))
                 and (col != "FREQUENCY" or r["PEAK_AMP"] >= 100.0)]  # D-030: judged only with a tone
            if len(v) > 1:
                ref[(step, f"ch{ch}")] = (st.mean(v), st.stdev(v), len(v))
    return ref


def analyze() -> bool:
    runs = load_records()
    if not runs:
        sys.exit(f"no records for {SERIAL} in {OUT / 'records'}")
    by_seq = defaultdict(list)
    for r in runs:
        by_seq[r["sequence"]].append(r)
    lines = ["# Gauge run for L-v1 (D-019 risk 3, D-051)", "",
             f"Device: Teensy USB serial 20071290 on the `teensy` fixture. DUT serial `{SERIAL}`. "
             f"Records: `records/`. Settings used: `settings_gauge.yaml`. Limit set in the records: "
             f"{', '.join(sorted({r['limit_set'] for r in runs}))}.", ""]

    # rule 1: errors
    errors = [r for r in runs if r["outcome"] in ("ERROR", "ABORTED")]
    lines += ["## 1. Errors", "", "| Sequence | Runs | PASS | FAIL | ERROR | ABORTED |",
              "|---|---|---|---|---|---|"]
    for seq, rs in by_seq.items():
        c = Counter(r["outcome"] for r in rs)
        lines.append(f"| {seq} | {len(rs)} | {c['PASS']} | {c['FAIL']} | {c['ERROR']} | {c['ABORTED']} |")
    for r in errors:
        detail = r["meta"]["context"].get("error_detail", "")
        lines.append(f"- {r['file']}: {r['outcome']} {r['error']} {detail}")
    rule1 = not errors

    # rule 2: verdicts
    false_fails = []
    failed_steps = defaultdict(Counter)  # (seq, sensor) -> step -> runs
    for r in runs:
        if r in errors:
            continue
        for ch, want in EXPECTED.items():
            mine = [x for x in r["rows"] if x["sensor"] == ch]
            fails = [x for x in mine if x["result"] == "FAIL"]
            prim = next((x["fault_family"] for x in mine if x["primary_failure"] == "True"), None)
            for x in fails:
                failed_steps[(r["sequence"], ch)][f"{x['step_id']} {x['step_name']}"] += 1
            if (prim if fails else None) != want:
                false_fails.append(f"{r['file']} {ch}: got {prim or 'PASS'}, expected {want or 'PASS'}")
    rule2 = not false_fails
    lines += ["", "## 2. Verdicts (zero false fails)", "",
              "| Sequence | Sensor | Expected | Steps failed (runs) |", "|---|---|---|---|"]
    for seq, rs in by_seq.items():
        n = len([r for r in rs if r not in errors])
        for ch, want in EXPECTED.items():
            steps = failed_steps[(seq, ch)]
            cells = ", ".join(f"{k} ({v}/{n})" for k, v in sorted(steps.items())) or "—"
            lines.append(f"| {seq} | {ch} | {want or 'PASS'} | {cells} |")
    lines += [f"- {x}" for x in false_fails] or [
        "", "Every run gave the expected verdict and primary failure on all 8 sensors."]

    # rule 3: drift vs DOE-1, as run and without the documented exclusions
    ref = doe_reference()
    excluded = [r for r in runs if r["run_id"] in EXCLUDED]
    values = defaultdict(list)  # (seq, step, sensor) -> values, every run
    kept = defaultdict(list)  # the same without the excluded runs
    for r in runs:
        if r in errors:
            continue
        for x in r["rows"]:
            if x["sensor"] != "RUN" and x["value"] != "" and x["step_name"] in DOE_REF:
                key = (r["sequence"], x["step_name"], x["sensor"])
                values[key].append(float(x["value"]))
                if r not in excluded:
                    kept[key].append(float(x["value"]))
    drift, drift_kept = [], []
    lines += ["", f"## 3. Drift since DOE-1 (gauge mean within {DRIFT_K:g} DOE-1 run-to-run SDs)", "",
              "Shift = (gauge mean − DOE-1 mean) ÷ DOE-1 run-to-run SD. SD ratio = gauge SD ÷ DOE-1 SD "
              "(repeatability today vs DOE-1; reported, not judged). Each is given as run, and without "
              f"the {len(excluded)} excluded run(s) listed below.", "",
              "| Sequence | Step | Sensor | Gauge mean (n) | DOE-1 mean (n) | Shift as run | Shift w/o excl. "
              "| SD ratio as run | SD ratio w/o excl. |",
              "|---|---|---|---|---|---|---|---|---|"]
    worst = worst_kept = 0.0
    for key, v in sorted(values.items()):
        seq, step, ch = key
        k = kept[key]
        if (step, ch) not in ref or len(v) < 2 or len(k) < 2:
            continue
        m0, s0, n0 = ref[(step, ch)]
        z, zk = ((st.mean(x) - m0) / s0 if s0 > 0 else 0.0 for x in (v, k))
        worst, worst_kept = max(worst, abs(z)), max(worst_kept, abs(zk))
        if abs(z) > DRIFT_K:
            drift.append(f"as run: {seq} {step} {ch}: shift {z:+.2f} SD")
        if abs(zk) > DRIFT_K:
            drift_kept.append(f"without exclusions: {seq} {step} {ch}: shift {zk:+.2f} SD")
        flag, flag_k = (" ⚠" if abs(x) > DRIFT_K else "" for x in (z, zk))
        lines.append(f"| {seq} | {step} | {ch} | {st.mean(v):.3f} ({len(v)}) | {m0:.3f} ({n0}) | "
                     f"{z:+.2f}{flag} | {zk:+.2f}{flag_k} | "
                     f"{st.stdev(v) / s0:.2f} | {st.stdev(k) / s0:.2f} |")
    rule3, rule3_kept = not drift, not drift_kept
    lines += [f"- {x}" for x in drift + drift_kept] or ["", f"Largest shift: {worst:.2f} SD."]
    lines += ["", "### Excluded from rule 3 (D-051)", ""]
    why = [f"| {r['run_id']} | {EXCLUDED[r['run_id']]} |" for r in excluded]
    lines += ["| Run | Why |", "|---|---|", *why] if excluded else ["None."]

    # validity and timing
    rates = [v for r in runs for v in r["meta"]["context"]["line_rate_hz"].values()]
    lines += ["", "## Validity and timing", "",
              f"- Line rate over {len(rates)} captures: {min(rates):.4f} to {max(rates):.4f} Hz.", ""]
    for seq, rs in by_seq.items():
        d = [r["meta"]["context"]["duration_s"]["total"] for r in rs]
        cmds = Counter(c["cmd"] for r in rs for c in r["meta"]["context"]["commands"])
        lines.append(f"- {seq}: run time {min(d):.2f}–{max(d):.2f} s (mean {st.mean(d):.2f}); "
                     f"commands sent: {dict(cmds)}.")

    passed = rule1 and rule2 and rule3
    accepted = rule1 and rule2 and rule3_kept
    verdict = ["", "## Result", "",
               f"- Rule 1, zero ERRORs: **{'PASS' if rule1 else 'FAIL'}**",
               f"- Rule 2, zero false fails: **{'PASS' if rule2 else 'FAIL'}**",
               f"- Rule 3, no drift since DOE-1, as run: **{'PASS' if rule3 else 'FAIL'}** "
               f"(largest shift {worst:.2f} SD)"]
    if excluded:
        verdict.append(f"- Rule 3 without the {len(excluded)} documented exclusion(s): "
                       f"**{'PASS' if rule3_kept else 'FAIL'}** (largest shift {worst_kept:.2f} SD)")
    if passed or not excluded:
        verdict += ["", f"**Gauge run {'PASSED' if passed else 'FAILED'}.**"]
    else:
        verdict += ["", f"**Gauge run FAILED as run; {'PASSED' if accepted else 'still FAILED'} with "
                        f"{len(excluded)} documented exclusion(s) (D-051).**"]
    lines[4:4] = [*verdict[1:], ""]
    (OUT / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(verdict))
    print(f"report: {OUT / 'report.md'}")
    return accepted


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("action", choices=["run", "analyze"])
    p.add_argument("--runs", type=int, default=20, help="runs per sequence")
    a = p.parse_args()
    if a.action == "run":
        if (OUT / "records").exists():
            sys.exit(f"{OUT / 'records'} already exists; analyze it, or move it away to re-run")
        run(a.runs)
    sys.exit(0 if analyze() else 1)


if __name__ == "__main__":
    main()
