"""Derive a TP-001 limit set from DOE-1 with the station's own code (D-050).

Replaces the exploration math of derive_limits_v0.py (kept unchanged as the record of how L-v0 was
made; its outputs are the golden files the tests compare against). Everything here is a call into
sensortest.characterization: the re-cut uses the plan's capture timing, the metrics are the
station's @metric functions, the rule is D-019, and the verdict table goes through the engine's
evaluation under the new limits.

Writes (refuses to overwrite unless --force):
  <out>/metric_table.csv        one row per run x sensor (same columns as recut_metrics.csv)
  <out>/limits_report.md        PROD verdicts over the tone runs, margins, the limit table
  <limits-file>                 the limit set YAML the plan compiler reads

Usage:
  python benchtop_testing/tools/derive_limits.py --limit-set L-v1 --status "frozen (gauge run ...)" \\
      --out benchtop_testing/08_limits_v2_derivation --limits-file config/TP-001_limits_v2.yaml
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import numpy as np
import yaml

BENCH = Path(__file__).resolve().parents[1]
REPO = BENCH.parent

from sensortest.app.settings import load_settings  # noqa: E402
from sensortest.characterization.limits import FREQ_TOL, TONE_PRESENT, derive_limits  # noqa: E402
from sensortest.characterization.recut import load_doe  # noqa: E402
from sensortest.characterization.table import metric_rows  # noqa: E402
from sensortest.characterization.verdicts import prod_run, summarize  # noqa: E402
from sensortest.plans.compiler import compile_plans  # noqa: E402

FIRST = ("sweep", "pos", "cmd", "ch", "f")
MESSAGE = {"frequency": "Wrong frequency", "noise": "Noisy", "offset": "Offset out of range",
           "gain": "Weak response / too strong"}


def plans_for(settings_path: Path, limits: Path):
    s = load_settings(settings_path)
    return compile_plans(s.sensor_tests, limits, s.plans, s.plan_constants), s


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--limit-set", required=True, help="e.g. L-v1")
    p.add_argument("--status", required=True, help="recorded in the limit set, e.g. why it's frozen")
    p.add_argument("--out", type=Path, required=True, help="folder for the metric table and report")
    p.add_argument("--limits-file", type=Path, required=True, help="the limit set YAML to write")
    p.add_argument("--doe", type=Path, default=BENCH / "03_doe1_repeatability")
    p.add_argument("--settings", type=Path, default=REPO / "config" / "settings.yaml")
    p.add_argument("--force", action="store_true", help="overwrite existing outputs")
    a = p.parse_args()

    table, report = a.out / "metric_table.csv", a.out / "limits_report.md"
    existing = [f for f in (table, report, a.limits_file) if f.exists()]
    if existing and not a.force:
        sys.exit(f"refusing to overwrite {', '.join(map(str, existing))} (use --force)")

    settings = load_settings(a.settings)
    plans, _ = plans_for(a.settings, settings.limits)  # timing + constants; limits not used here
    runs = load_doe(a.doe, plans["ENG"])
    rows = metric_rows(runs, plans["ENG"])
    limits = derive_limits(rows, plans["ENG"], a.limit_set, a.status)

    a.out.mkdir(parents=True, exist_ok=True)
    keys = sorted({k for r in rows for k in r}, key=lambda k: (k not in FIRST, FIRST.index(k) if k in FIRST else 0, k))
    with table.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, keys)
        w.writeheader()
        w.writerows(rows)
    header = (f"# {limits['plan']} limit set {a.limit_set}. GENERATED by benchtop_testing/tools/derive_limits.py\n"
              "# from DOE-1 with the station's own code (D-050); edit the derivation, not this file.\n")
    a.limits_file.parent.mkdir(parents=True, exist_ok=True)
    a.limits_file.write_text(header + yaml.safe_dump(limits, sort_keys=False, allow_unicode=True), encoding="utf-8")

    new_plans, _ = plans_for(a.settings, a.limits_file)  # verdicts under the new limits
    tone_runs = [r for r in runs if r.tone_hz is not None]
    summary = summarize(prod_run(new_plans["PROD"], r) for r in tone_runs)
    report.write_text(render(rows, limits, summary, len(tone_runs)), encoding="utf-8")
    print(f"wrote {table} ({len(rows)} rows), {a.limits_file}, {report}")


def render(rows, limits, summary, n_tone) -> str:
    steps = limits["steps"]
    out = [f"# {limits['plan']} limits {limits['limit_set']}: derivation check", "",
           "Source: DOE-1 re-cut to the plan's capture timing with the station's code (D-050). Each tone run "
           "stands in for T10, measured at its own commanded f.", "",
           f"## PROD verdicts over {n_tone} simulated runs (BL + one tone each), through the engine's evaluation", "",
           "| Sensor | PASS runs | FAIL runs | Primary failure (count) | Steps failed (count) |", "|---|---|---|---|---|"]
    for s, v in summary.items():
        prim = ", ".join(f"{MESSAGE.get(k, k)} ({n})" for k, n in v.primary.items()) or "—"
        failed = ", ".join(f"{k} ({n})" for k, n in sorted(v.steps.items())) or "—"
        out.append(f"| {s} | {v.passed} | {v.failed} | {prim} | {failed} |")

    def vals(key, ch, tone):
        return np.array([r[key] for r in rows if r["ch"] == ch and key in r and (not tone or r["cmd"] != "control")])

    out += ["", "## Margins: distance from each sensor's mean to the nearest limit (in its own run-to-run SDs)", "",
            "| Sensor | 2040 offset | 2050 noise | 6040 amplitude | 6050 frequency (judged runs) |",
            "|---|---|---|---|---|"]
    for ch in range(1, 9):
        cells = []
        for key, sid, tone in (("BL_OFFSET", "2040 BL_OFFSET", False), ("BL_NOISE_STD", "2050 BL_NOISE_STD", False),
                               ("AMPLITUDE", "6040 T10_AMPLITUDE", True)):
            v = vals(key, ch, tone)
            lo, hi = steps[sid]["low"], steps[sid]["high"]
            cells.append(f"{min(v.mean() - lo, hi - v.mean()) / v.std(ddof=1):+.1f}")
        fe = np.array([r["FREQ_ERR"] for r in rows if r["ch"] == ch and "PEAK_AMP" in r and r["PEAK_AMP"] >= TONE_PRESENT])
        cells.append(f"{(FREQ_TOL - abs(fe.mean())) / fe.std(ddof=1):+.1f} ({len(fe)} judged)" if len(fe) > 1
                     else "not judged (no tone)")
        out.append(f"| ch{ch} | " + " | ".join(cells) + " |")

    out += ["", f"## Limits ({limits['limit_set']})", "", "| Step | Low | High | Unit | Method | Sequences |",
            "|---|---|---|---|---|---|"]
    for sid, d in steps.items():
        out.append(f"| {sid} | {d['low']} | {d['high']} | {d['unit']} | {d['method']} | {', '.join(d['sequences'])} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    main()
